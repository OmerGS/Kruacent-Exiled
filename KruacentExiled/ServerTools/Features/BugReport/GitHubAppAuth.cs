using System;
using System.IO;
using System.Net;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;

namespace KruacentExiled.ServerTools.Features.BugReport
{
    /// <summary>
    /// Authenticates as a GitHub App so the server can create issues without a personal account.
    /// It signs a short-lived JWT with the App private key, exchanges it for an installation
    /// token (valid 1 h, limited to the repository) and caches that token until it expires.
    /// <para>
    /// Everything is done by hand (JWT signing, PEM/DER key parsing, JSON reading) because the
    /// plugin ships as a single DLL: a NuGet package such as Octokit or a JWT library would add
    /// extra DLLs (4 new DLL) that every server owner would have to install in the EXILED dependencies folder.
    /// .NET Framework 4.8 alone cannot read a .pem key or build a JWT, hence this code.
    /// </para>
    /// <para>Generated by AI.</para>
    /// </summary>
    internal static class GitHubAppAuth
    {
        // GitHub tokens last 1 h; we renew a bit earlier so we never send an expired token.
        private static readonly TimeSpan TokenLifetime = TimeSpan.FromMinutes(50);

        private static readonly object tokenLock = new object();
        private static string installationToken;
        private static DateTime tokenExpiresAt;
        private static long installationId;

        public static string GetInstallationToken(string appId, string privateKeyFile, string repository)
        {
            // Several reports at the same time: only one thread requests a new token.
            lock (tokenLock)
            {
                if (installationToken != null && DateTime.UtcNow < tokenExpiresAt)
                {
                    return installationToken;
                }

                string jwt = CreateJwt(appId, File.ReadAllText(privateKeyFile));

                // The installation id never changes: we only request it once.
                if (installationId == 0)
                {
                    string installation = Request("GET", "https://api.github.com/repos/" + repository + "/installation", jwt, null);
                    installationId = long.Parse(ReadJsonValue(installation, "id"));
                }

                string response = Request("POST", "https://api.github.com/app/installations/" + installationId + "/access_tokens", jwt, "");
                installationToken = ReadJsonValue(response, "token");
                tokenExpiresAt = DateTime.UtcNow + TokenLifetime;

                return installationToken;
            }
        }

        public static string Request(string method, string url, string bearer, string json)
        {
            ServicePointManager.SecurityProtocol |= SecurityProtocolType.Tls12;

            using (WebClient client = new WebClient())
            {
                client.Encoding = Encoding.UTF8;
                client.Headers[HttpRequestHeader.UserAgent] = "KruacentExiled-BugReport";
                client.Headers[HttpRequestHeader.Accept] = "application/vnd.github+json";
                client.Headers[HttpRequestHeader.Authorization] = "Bearer " + bearer;

                try
                {
                    if (json == null)
                    {
                        return client.DownloadString(url);
                    }

                    client.Headers[HttpRequestHeader.ContentType] = "application/json";
                    return client.UploadString(url, method, json);
                }
                catch (WebException e)
                {
                    // Add the failing URL and GitHub's own explanation to the error.
                    throw new WebException(method + " " + url + " failed: " + e.Message + " " + ReadErrorBody(e), e);
                }
            }
        }

        private static string ReadErrorBody(WebException e)
        {
            if (e.Response == null)
            {
                return "";
            }

            using (StreamReader reader = new StreamReader(e.Response.GetResponseStream()))
            {
                return reader.ReadToEnd();
            }
        }

        // Signed token proving to GitHub that we own the App private key (valid for 9 min).
        private static string CreateJwt(string appId, string privateKeyPem)
        {
            long now = DateTimeOffset.UtcNow.ToUnixTimeSeconds();

            string header = Base64Url(Encoding.UTF8.GetBytes("{\"alg\":\"RS256\",\"typ\":\"JWT\"}"));
            // iat 60 s in the past: tolerates a server clock running slightly ahead.
            string payload = Base64Url(Encoding.UTF8.GetBytes("{\"iat\":" + (now - 60) + ",\"exp\":" + (now + 540) + ",\"iss\":\"" + appId + "\"}"));
            string unsigned = header + "." + payload;

            using (RSACryptoServiceProvider rsa = new RSACryptoServiceProvider())
            {
                rsa.ImportParameters(ReadRsaPrivateKey(privateKeyPem));

                byte[] signature = rsa.SignData(Encoding.UTF8.GetBytes(unsigned), new SHA256CryptoServiceProvider());
                return unsigned + "." + Base64Url(signature);
            }
        }

        private static string Base64Url(byte[] data)
        {
            return Convert.ToBase64String(data).TrimEnd('=').Replace('+', '-').Replace('/', '_');
        }

        // Looks for "name": value in the GitHub JSON response (string or number).
        private static string ReadJsonValue(string json, string name)
        {
            Match match = Regex.Match(json, "\"" + name + "\"\\s*:\\s*\"?([^\",}]+)");
            if (!match.Success)
            {
                throw new InvalidDataException("Field '" + name + "' missing from the GitHub response");
            }

            return match.Groups[1].Value;
        }

        // .NET Framework 4.8 cannot read a .pem file: we parse the "BEGIN RSA PRIVATE KEY"
        // (PKCS#1 format) key provided by GitHub ourselves.
        private static RSAParameters ReadRsaPrivateKey(string pem)
        {
            if (!pem.Contains("BEGIN RSA PRIVATE KEY"))
            {
                throw new InvalidDataException("The key must be the .pem downloaded from the GitHub App (BEGIN RSA PRIVATE KEY)");
            }

            string base64 = Regex.Replace(pem, "-----[^-]+-----|\\s", "");
            DerReader der = new DerReader(Convert.FromBase64String(base64));

            der.ReadSequenceStart();
            der.ReadInteger(); // version

            byte[] modulus = der.ReadInteger();
            byte[] exponent = der.ReadInteger();
            byte[] d = der.ReadInteger();
            byte[] p = der.ReadInteger();
            byte[] q = der.ReadInteger();
            byte[] dp = der.ReadInteger();
            byte[] dq = der.ReadInteger();
            byte[] inverseQ = der.ReadInteger();

            // RSACryptoServiceProvider requires exact sizes: we pad with zeros on the left.
            int size = modulus.Length;
            int half = (size + 1) / 2;

            return new RSAParameters
            {
                Modulus = modulus,
                Exponent = exponent,
                D = PadLeft(d, size),
                P = PadLeft(p, half),
                Q = PadLeft(q, half),
                DP = PadLeft(dp, half),
                DQ = PadLeft(dq, half),
                InverseQ = PadLeft(inverseQ, half),
            };
        }

        private static byte[] PadLeft(byte[] value, int length)
        {
            if (value.Length >= length)
            {
                return value;
            }

            byte[] padded = new byte[length];
            Buffer.BlockCopy(value, 0, padded, length - value.Length, value.Length);
            return padded;
        }

        /// <summary>Minimal reader for the DER binary format (just enough for an RSA key).</summary>
        private sealed class DerReader
        {
            private readonly byte[] data;
            private int position;

            public DerReader(byte[] data)
            {
                this.data = data;
            }

            public void ReadSequenceStart()
            {
                Expect(0x30);
                ReadLength();
            }

            public byte[] ReadInteger()
            {
                Expect(0x02);
                int length = ReadLength();

                // DER prepends a 0 to numbers whose first bit is 1: we strip it.
                int start = position;
                while (length > 1 && data[start] == 0)
                {
                    start++;
                    length--;
                }

                byte[] value = new byte[length];
                Buffer.BlockCopy(data, start, value, 0, length);
                position = start + length;
                return value;
            }

            private void Expect(byte tag)
            {
                if (data[position++] != tag)
                {
                    throw new InvalidDataException("Unreadable private key");
                }
            }

            private int ReadLength()
            {
                int length = data[position++];
                if (length < 0x80)
                {
                    return length;
                }

                // Long form: the following bytes give the length.
                int byteCount = length & 0x7F;
                length = 0;
                for (int i = 0; i < byteCount; i++)
                {
                    length = (length << 8) | data[position++];
                }

                return length;
            }
        }
    }
}